export function getTranslation(lang, key, params = {}) {
  const dict = translations[lang] || translations.vi;
  let text = dict[key] || translations.vi[key] || key;
  Object.keys(params).forEach(p => {
    text = text.replace(`{${p}}`, params[p]);
  });
  return text;
}
